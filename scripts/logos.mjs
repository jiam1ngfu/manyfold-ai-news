async function get(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  return response.text();
}

/** Downloaded markup is untrusted: keep plain shapes only, then refuse anything active or external. */
function clean(svg, key, fill) {
  let out = svg
    .replace(/<title>[\s\S]*?<\/title>/g, '')
    .replace(/\s(width|height|style|role|class)="[^"]*"/g, '')
    .replace(/currentColor/g, '#000')
    .replace(/\s+/g, ' ')
    .replace(/> </g, '><')
    .trim();
  if (fill) out = out.replace(/^<svg\b/, `<svg fill="#${fill}"`);
  const bad = [
    [/^(?!<svg\b)|(?<!<\/svg>)$/, 'not a single <svg> element'],
    [/<(script|style|foreignObject|image|iframe|a)\b/i, 'active or embedded element'],
    [/\son[a-z]+\s*=/i, 'event handler'],
    [/<!|<\?/, 'doctype, entity or processing instruction'],
    [/(?:xlink:)?href\s*=\s*"(?!#)/i, 'external reference'],
    [/url\(\s*(?!#)/i, 'external url()'],
  ];
  for (const [pattern, what] of bad) if (pattern.test(out)) throw new Error(`${key}: ${what}`);
  return out;
}

/** Compact data URL: single quotes inside, and only the characters URLs need escaped. */
function dataUrl(svg) {
  const escaped = svg.replace(/[%#<>?[\\\]^`{|}]/g, (c) => encodeURIComponent(c));
  return `data:image/svg+xml,${svg.includes("'") ? escaped.replace(/"/g, '%22') : escaped.replace(/"/g, "'")}`;
}

